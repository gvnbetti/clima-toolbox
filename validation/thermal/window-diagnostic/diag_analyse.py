"""Window diagnostic, step 4: pooled over the 14 climates and the light and heavy box (600FF, 900FF):
- the share of the sun transmitted through the windows that EnergyPlus absorbs on opaque inside surfaces;
- the sun through the glass relative to the flush windows, in EnergyPlus and in the app, over the year and in
  June to August (all 14 climates lie in the northern hemisphere);
- the app engine against EnergyPlus, as written, with each change alone and with all four: degree-hours above
  26 degC and the bias of the hourly air temperature.
Writes results.md and summary.json next to this script."""
import json, os, sys, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "lib")); sys.path.insert(0, os.path.join(HERE, "..", "engine"))
from paths import WORK
import climates
from diag_cases import GEOMS, BASES
D = os.path.join(WORK, "window_diag"); C = json.load(open(os.path.join(D, "cases.json")))
VARS = {"written": "as written", "wind": "+ (1) wind", "angle": "+ (2) angle", "opaque": "+ (3) sun on opaque", "sky": "+ (4) sky", "room": "all four"}
LAB = {"flush": "Flush, as Standard 140", "reveal": "0.3 m outer reveal", "frame": "30 % frame", "recess": "Reveal and frame, as Room Clima",
       "single": "One window instead of two", "recess_dark0": "Reveal and frame, frame absorbs no sun"}
ld = lambda *p: json.load(open(os.path.join(D, *p)))
kh = lambda t: float(np.clip(np.array(t) - 26, 0, None).sum())
glass = lambda z: sum(e["area"] * (1 - e["geom"].get("frame", 0)) for e in z["elements"] if e["kind"] == "window")
S = {}
for g in GEOMS:
    tr = op = 0; sun = {"ep": [0, 0], "js": [0, 0]}; K = {v: [0, 0] for v in VARS}; B = {v: [] for v in VARS}
    for b in BASES:
        c = f"{b}_{g}"
        for clim in climates.CLIMATES:
            e = ld("ep", clim, c + ".json"); tr += e["transmitted"]; op += e["opaque"]; te = np.array(e["tair"])
            j = ld("js", "sun", clim, c + ".json")["monthly"]
            sun["ep"][0] += sum(e["monthly"]); sun["ep"][1] += sum(e["monthly"][5:8]); sun["js"][0] += sum(j); sun["js"][1] += sum(j[5:8])
            for v in VARS:
                t = np.array(ld("js", v, clim, c + ".json")["tair"]); K[v][0] += kh(t); K[v][1] += kh(te); B[v].append(float((t - te).mean()))
    S[g] = dict(glass=glass(C[f"600FF_{g}"]), kept=100 * op / tr, sun=sun, ohEP=K["written"][1] / len(BASES) / len(climates.CLIMATES),
                dev={v: 100 * (K[v][0] / K[v][1] - 1) for v in VARS}, bias={v: float(np.mean(B[v])) for v in VARS})
F = S["flush"]
L = ["# Window diagnostic: why the app engine runs warm in the Standard 140 box", "",
     "Generated by `diag_analyse.py`. Free-floating cases 600FF (light) and 900FF (heavy) in the 14 climates of the engine study, with six window geometries (`diag_cases.py`).", "",
     "## Where the transmitted sun goes, and how much gets through", "",
     "Kept: share of the sun transmitted through the glass that EnergyPlus absorbs on opaque inside surfaces (walls, roof, floor, frame); the rest is absorbed by the glass from inside or leaves through it. Change 3 assumes 100 %. Sun through the glass: relative to the flush windows, over the year and in June to August.", "",
     "| Window | Glass (m²) | Kept by EnergyPlus | Sun through the glass, year: EnergyPlus / app | June to August: EnergyPlus / app | EnergyPlus degree-hours > 26 °C (K·h, mean per case) |",
     "|---|---|---|---|---|---|"]
for g, s in S.items():
    r = lambda m, k: s["sun"][m][k] / F["sun"][m][k]
    L.append(f"| {LAB[g]} | {s['glass']:.1f} | {s['kept']:.1f} % | {r('ep', 0):.3f} / {r('js', 0):.3f} | {r('ep', 1):.3f} / {r('js', 1):.3f} | {s['ohEP']:,.0f} |")
L += ["", "## The app engine against EnergyPlus", "",
      "Degree-hours above 26 °C, deviation from EnergyPlus; mean bias of the hourly air temperature in brackets.", "",
      "| Window | " + " | ".join(VARS.values()) + " |", "|---|" + "---|" * len(VARS)]
for g, s in S.items():
    L.append(f"| {LAB[g]} | " + " | ".join(f"{s['dev'][v]:+.1f} % ({s['bias'][v]:+.2f} K)" for v in VARS) + " |")
open(os.path.join(HERE, "results.md"), "w").write("\n".join(L) + "\n")
json.dump(S, open(os.path.join(HERE, "summary.json"), "w"), indent=1)
print("\n".join(L))
