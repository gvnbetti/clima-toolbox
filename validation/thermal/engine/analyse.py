def load(model, clim, case):
    f = os.path.join(D, "ep" if model == "ep" else os.path.join("js", model), clim, case + ".json")
    return json.load(open(f))

def summ(r, area=48.0):
    t = r["tair"]; o = {"tmax": max(t), "tmin": min(t)}
    if "qh" in r:
        o.update({"heat": sum(r["qh"]) / 1e6, "cool": sum(r["qc"]) / 1e6, "pheat": max(r["qh"]) / 1000, "pcool": max(r["qc"]) / 1000})   # MWh, kW
    return o

# Standard 140-2020 example results of six programs (BSIMAC, CSE, DeST, EnergyPlus, ESP-r, TRNSYS) and Addendum b acceptance
