"""Scores the engine test. Part 1: ASHRAE Standard 140-2020 in Denver, against the acceptance ranges of Addendum b
(annual loads) and the range of the six reference programs (peak loads, free-floating temperatures). Part 2: the app
engine against EnergyPlus in 14 climates. Writes results.md and summary.json next to this script."""
import json, os, sys, statistics as st, math
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
from paths import WORK
