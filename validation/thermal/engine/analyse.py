per_case = {}
for m, label in MODELS.items():
    res = {c: summ(load(m, "denver", c)) for c in SPEC["cases"]}
    n = inn = 0; dev = {}; miss = []
    for metric, cases in REF.items():
        for c, vals in cases.items():
            v = res[c][metric]; lo, hi = LIMITS.get(metric, {}).get(c, (min(vals), max(vals)))
            ok = lo - 1e-9 <= round(v, 3) <= hi + 1e-9; n += 1; inn += ok
